#!/usr/bin/env bash
# Verify the merged release dist carries exactly its tag-matched SBOM.
#
# Usage: scripts/check-dist-sbom.sh <version> [dist-dir] [--against-lockfile]
#   → asserts dist/brain-server-<version>.cdx.json exists, reports the
#     requested version inside its CycloneDX metadata, and that no other
#     SBOM sits beside it. Fail-closed on all three (nonzero exit,
#     nothing published by the caller).
#
# `--against-lockfile` ADDS the fourth check: every component the shipped
# manifest names must be at the version the COMMITTED lockfile pins, and a
# manifest that names NO components is refused. It is a flag because it needs
# a real manifest to mean anything — the version-and-uniqueness contract above
# is what a fixture with no components can exercise, and this one is what the
# release path runs.
#
# The fourth check is the one that makes the first three mean something. The
# dist SBOM is generated by the build job AFTER the build, from whatever
# lockfile the build left on disk; the committed one is what the dependency
# audit actually read. If a build re-resolved the lockfile, the two would
# describe DIFFERENT dependency sets and the release would ship bytes that
# no audit ever saw. The comparison is against the COMMITTED lockfile
# (`git show HEAD:Cargo.lock`, so a build's in-place edit cannot hide), and
# it is per-component-version rather than a set comparison: cargo-cyclonedx
# filters by HOST platform (the committed macOS manifest carries `objc2` and
# no `windows-sys`; the release's Linux manifest carries neither), so the two
# component SETS legitimately differ while the VERSIONS must not.
#
# Kept as a file (not inline workflow Python) because run-block quoting
# layers do not survive the transport intact; a script file executes
# byte-identically everywhere.
set -euo pipefail

VERSION="${1:?usage: check-dist-sbom.sh <version> [dist-dir] [--against-lockfile]}"
shift
DIST="dist"
AGAINST_LOCKFILE=0
for arg in "$@"; do
  case "$arg" in
    --against-lockfile) AGAINST_LOCKFILE=1 ;;
    *) DIST="$arg" ;;
  esac
done
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

SBOM="$DIST/brain-server-${VERSION}.cdx.json"
[[ -f "$SBOM" ]] || { echo "ERR: required SBOM missing: $SBOM" >&2; exit 1; }

ACTUAL="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["metadata"]["component"]["version"])' "$SBOM")"
[[ "$ACTUAL" == "$VERSION" ]] || {
  echo "ERR: SBOM version mismatch: $SBOM reports '$ACTUAL', want '$VERSION'" >&2
  exit 1
}

EXTRA="$(ls "$DIST"/*.cdx.json 2>/dev/null | grep -v -F "$SBOM" || true)"
[[ -z "$EXTRA" ]] || {
  echo "ERR: historical SBOMs in $DIST (only $SBOM ships): $EXTRA" >&2
  exit 1
}

if [[ "$AGAINST_LOCKFILE" == "1" ]]; then
# The COMMITTED lockfile, not the one on disk: the build may have written to
# it, and the whole point is to compare against what the audit read.
LOCK=""
if git -C "$REPO" rev-parse --verify HEAD >/dev/null 2>&1; then
  LOCK="$(git -C "$REPO" show HEAD:Cargo.lock 2>/dev/null || true)"
fi
[[ -n "$LOCK" ]] || LOCK="$(cat "$REPO/Cargo.lock" 2>/dev/null || true)"
[[ -n "$LOCK" ]] || { echo "ERR: no committed Cargo.lock to compare the SBOM against" >&2; exit 1; }

python3 - "$SBOM" "$REPO" "$LOCK" <<'PY'
import json, re, sys

sbom_path, repo, lock_text = sys.argv[1], sys.argv[2], sys.argv[3]

# The lockfile's (name, version) pairs. A crate can appear at TWO versions
# (webpki-roots 0.26.11 and 1.0.10, rsa 0.9.10 and 0.10.0-rc.19), so the set
# carries both and the comparison is per PAIR, not per name.
pinned = set(
    (m.group(1), m.group(2))
    for m in re.finditer(r'name = "([^"]+)"\nversion = "([^"]+)"', lock_text)
)

components = json.load(open(sbom_path)).get("components", [])
if not components:
    print("ERR: the SBOM names no components — a manifest that lists nothing "
          "would satisfy every comparison", file=sys.stderr)
    raise SystemExit(1)

offenders = []
for c in components:
    name, version = c.get("name"), c.get("version")
    if not name or not version:
        offenders.append(f"{name!r} {version!r} (a component with no name or version)")
        continue
    if (name, version) not in pinned:
        offenders.append(f"{name} {version} (not pinned at that version in the committed Cargo.lock)")

if offenders:
    print("ERR: the shipped SBOM and the committed Cargo.lock disagree — the "
          "release's dependency set is not the audited one:", file=sys.stderr)
    for o in offenders[:20]:
        print(f"  {o}", file=sys.stderr)
    if len(offenders) > 20:
        print(f"  ... and {len(offenders) - 20} more", file=sys.stderr)
    raise SystemExit(1)

print(f"OK  {sbom_path}: {len(components)} components, every one at the "
      f"version the committed Cargo.lock pins")
PY
fi

echo "OK  dist carries exactly $(basename "$SBOM")"
